/* Life situations — Story mode.
   Every scene is built from the app's phrase kit ({…} = a phrase from kit.js), the 3,000 words ([word] or [word|shown form])
   and the grammar lessons (a line [who, text, "gram"] with *marked words* becomes a real example in that lesson).
   All characters, stories and dialogue are original. */
const LIFE = (function(){
  const norm=s=>String(s).toLowerCase().replace(/[’‘]/g,"'").replace(/…/g,"").replace(/[^a-z0-9' ]/g," ").replace(/\s+/g," ").trim();
  const KT={}; KIT.forEach(p=>p.chunks.forEach((c,i)=>{ KT[norm(c[0])]={key:`c:${p.id}:${i}`,p,c}; }));
  const VT={}; WORDS.forEach((w,i)=>{ if(VT[w[0]]==null) VT[w[0]]=i; });
  const slug=s=>norm(s).replace(/[^a-z0-9]+/g,"_").replace(/^_|_$/g,"").slice(0,36);
  const CH=[
    {n:1,name:"Home life",blurb:"Mornings, roommates, chores, phone calls."},
    {n:2,name:"Food & drinks",blurb:"Cafés, restaurants, bars and parties."},
    {n:3,name:"Around town",blurb:"Shops, streets, returns and the doctor."},
    {n:4,name:"Work",blurb:"Interviews, first days, meetings, bosses."},
    {n:5,name:"Friends & love",blurb:"Catching up, dates, parents, bad news."},
    {n:6,name:"Trips & weekends",blurb:"Hotels, the beach, the park, cooking for friends."}];
  const PX={}; const SCENES={}; const GX={}; const errors=[];
  function phrase(text){
    const k=KT[norm(text)];
    if(k){ const key="k_"+k.key.slice(2).replace(":","_");
      if(!W[key]) W[key]={cat:"phrase",text:k.c[0].replace(/^…/,"").replace(/…$/,"…"),tag:"phrase · "+k.p.name.toLowerCase(),def:k.c[1],ex:"When: "+k.c[2],kit:k.key};
      return key; }
    const x=PX[text];
    if(x){ const key="x_"+slug(text); if(!W[key]) W[key]={cat:"phrase",text,tag:"phrase · "+(x[2]||"real talk"),def:x[0],ex:x[1]||""}; return key; }
    errors.push("unknown phrase: "+text); return null;
  }
  function word(k){
    if(W[k]){ const i=VT[String(W[k].word||k).toLowerCase()]; if(i!=null&&W[k].voc==null&&W[k].cat!=="phrase") W[k].voc=i; return k; }
    const i=VT[k.toLowerCase()]; if(i==null){ errors.push("unknown word: "+k); return null; }
    const w=WORDS[i]; W[k]={cat:"vocab",word:w[0],tag:"word · #"+(i+1),def:w[2],ex:w[3].replace(/\*/g,""),emo:w[1],voc:i}; return k;
  }
  function text(s){
    s=s.replace(/\{([^}]+)\}/g,(m,t0,off,str)=>{ const [t,given]=t0.split("|"); const k=phrase(t); if(!k) return given||t;
      let shown=given||t; const after=str.slice(off+m.length);
      if(/^ ?[a-z]/.test(after)) shown=shown.replace(/[.?!…]+$/,"");
      return shown===W[k].text?"["+k+"]":"["+k+"|"+shown+"]"; });
    for(const m of s.matchAll(/\[([^\]|]+)(?:\|[^\]]+)?\]/g)) word(m[1]);
    return s;
  }
  function px(table){ Object.assign(PX,table); }
  // grammar points that are easy to spot also become examples automatically (the matched words are highlighted)
  const AUTO=[["g_wanna",/\b(?:wanna|gonna|gotta|kinda)\b/gi],["g_tags",/, (?:right|huh|isn't it|aren't you|isn't he|don't you|didn't you|won't you)\?/gi],
    ["g_phrasal",/\b(?:take|takes|took|turn|turned|show|showed|check|pick|picked|give|gave|hang|hanging|figure|sort|look|looking|get|got|come|log|cheer|end|ended|run|ran|break|broke|move|moving|work|worked) (?:out|up|down|in|off|on|around|over|forward to)\b/gi],
    ["g_some",/\b(?:some|any)\b/gi],["g_should",/\b(?:should|shouldn't|have to|has to)\b/gi],["g_lets",/\blet's\b/gi],
    ["g_best",/\b(?:the best|the worst|better than|worse than|the \w{3,}est)\b/gi],["g_can",/\b(?:can I|could you|could I|can you)\b/gi]];
  const plainOf=t=>t.replace(/\[([^\]|]+)(?:\|([^\]]+))?\]/g,(m,k,sh)=>sh||(W[k]&&(W[k].text||W[k].word))||k).replace(/\*/g,"");
  function autoGram(id,nid,who,tt,explicit){
    const p=plainOf(tt);
    for(const [gid,re] of AUTO){ if(gid===explicit) continue; re.lastIndex=0; if(!re.test(p)) continue; re.lastIndex=0;
      (GX[gid]=GX[gid]||[]).push([id,p.replace(re,m=>"*"+m+"*"),who,nid]); }
  }
  function sc(id,ch,place,title,brief,nodes){
    const out={level:ch,title,place,brief,start:"s",nodes:{}};
    for(const [nid,n] of Object.entries(nodes)){
      const lines=(n.l||[]).map(l=>{
        if(typeof l==="string") return text(l).replace(/\*/g,"");
        const [who,t,g]=l; const tt=text(t);
        if(g){ const gid="g_"+g; (GX[gid]=GX[gid]||[]).push([id,tt,who,nid]); }
        autoGram(id,nid,who,tt,g?"g_"+g:null);
        return [who,tt.replace(/\*/g,"")];
      });
      const cards={};
      if(n.c) for(const [k,v] of Object.entries(n.c)){
        const key = W[k] ? k : (VT[k]!=null && /^[a-z]+$/.test(k)) ? word(k) : phrase(k);
        if(key){ cards[key]=v; if(!nodes[v]) errors.push(`${id}: card "${k}" goes to missing node ${v}`); }
      }
      if(n.do) n.do.forEach(op=>{ if(op[0]==="add" && !W[op[1]]) word(op[1]); });
      out.nodes[nid]=n.end?{do:n.do||[],lines,end:n.end}:{do:n.do||[],lines,ask:n.ask||"What do you say?",cards};
      if(!n.end && !Object.keys(cards).length) errors.push(`${id}.${nid}: no cards`);
    }
    SCENES[id]=out;
    W[id]={cat:"place",word:title,tag:"scene · "+CH[ch-1].name.toLowerCase(),def:brief,ex:"",place};
  }
  // sentence patterns (kit.js PATTERNS) found in the scenes' lines
  const PRE=[["I'm thinking about",/\bthinking about \w+ing\b/i],["I've been meaning to",/\bbeen meaning to\b/i],["I feel like",/\bfeel like \w+ing\b/i],
    ["I'm about to",/\b(?:'m|'re|'s|am|is|are) about to\b/i],["I used to",/\bused to (?!be used)\w+(?<!ing)\b/i],["I'm used to",/(?:'m|'re|'s|\bam|\bis|\bare|\bget|\bgot) used to \w+ing\b/i],
    ["I wish I could",/\bwish I could\b/i],["If I were you",/\bif I were you\b/i],["Why don't we",/\bwhy don't we\b/i],["How about",/\bhow about \w+ing\b/i],
    ["Do you mind if I",/\bdo you mind if I\b/i],["I'd rather",/(?:I|we|you)'d rather\b/i],["I'm supposed to",/(?:'m|'re|'s|\bam|\bis|\bare|\bwas|\bwere) supposed to\b/i],
    ["I ended up",/\bended up \w+ing\b/i],["I can't stand",/\bcan't stand\b/i],["I'm (really) into",/(?:'m|'re|\bis|\bam|\bare) (?:really |so )?into\b/i],
    ["I'm not a big fan of",/\bnot a big fan of\b/i],["Have you ever",/\bhave you ever\b/i],["How long have you been",/\bhow long have you been\b/i],
    ["It depends on",/\bit depends on\b/i],["There's no way",/\bthere's no way\b/i],["Let me know if",/\blet me know if\b/i],["I'm gonna have to",/\bgonna have to\b/i],
    ["It's worth",/\bit's worth \w+ing\b/i],["You should have",/\bshould(?: have|'ve) \w+(?:ed|en|ne|ld|ght|id|ent|un)\b/i],["What if",/\bwhat if\b/i],
    ["I'm not sure if",/\bnot sure if\b/i],["The thing is",/\bthe thing is\b/i]];
  const PT={};
  function findPatterns(){
    for(const k of Object.keys(PT)) delete PT[k];
    const idx=PRE.map(([f])=>PATTERNS.findIndex(p=>p[0].startsWith(f)));
    idx.forEach((i,j)=>{ if(i<0) errors.push("pattern not found: "+PRE[j][0]); });
    const plainT=t=>t.replace(/\[([^\]|]+)(?:\|([^\]]+))?\]/g,(m,k,sh)=>sh||(W[k]&&(W[k].text||W[k].word))||k);
    for(const [id,s] of Object.entries(SCENES)) for(const [nid,n] of Object.entries(s.nodes)) for(const l of n.lines){
      const who=Array.isArray(l)?l[0]:null; if(!who) continue; const t=plainT(l[1]);
      PRE.forEach(([f,re],j)=>{ if(idx[j]>=0 && re.test(t)) (PT[idx[j]]=PT[idx[j]]||[]).push([id,nid,t,who]); });
    }
  }
  return {CH,SCENES,GX,PT,errors,sc,px,findPatterns,
    install(){ findPatterns(); for(const k of Object.keys(SC)) delete SC[k]; Object.assign(SC,SCENES); LEVELS.length=0; CH.forEach(c=>LEVELS.push(c)); }};
})();
